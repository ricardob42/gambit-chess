// Spanish is the default language.
export const i18n = $state({ lang: localStorage.getItem(KEY) ?? 'es' });

export function setLang(lang) {
  i18n.lang = lang;
  localStorage.setItem(KEY, lang);
}

export function t(key, params) {
  const text = DICT[i18n.lang][key];
  return params ? text.replace(/\{(\w+)\}/g, (_, name) => params[name]) : text;
}

const SPANISH_PIECES = { N: 'C', B: 'A', R: 'T', Q: 'D', K: 'R' };

// Spanish notation uses C, A, T, D, R for knight, bishop, rook, queen, king.
export const san = (move) => (i18n.lang === 'es' ? move.replace(/[NBRQK]/g, (l) => SPANISH_PIECES[l]) : move);
